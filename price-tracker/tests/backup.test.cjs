const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const sandbox={URL,Intl,Date};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../lib/core.js'),'utf8'),sandbox);
const {backupRecommended,DAY}=sandbox.PriceCore;
const now=Date.parse('2026-11-23T03:00:00Z');
const state={products:{a:{records:{'2026-11-23':{sale:1000}}}}};
assert.equal(backupRecommended({products:{}},now),false);
assert.equal(backupRecommended({products:{a:{records:{}}}},now),false);
assert.equal(backupRecommended(state,now),true);
state.lastCsvExportAt=new Date(now-7*DAY+1).toISOString();
assert.equal(backupRecommended(state,now),false);
state.lastCsvExportAt=new Date(now-7*DAY).toISOString();
assert.equal(backupRecommended(state,now),true);
state.lastCsvExportAt=new Date(now-8*DAY).toISOString();
assert.equal(backupRecommended(state,now),true);
state.lastCsvExportAt=new Date(now).toISOString();
assert.equal(backupRecommended(state,now),false);
state.lastCsvExportAt='invalid';
assert.equal(backupRecommended(state,now),true);
console.log('PASS backup reminder: no records, first export, exact 168-hour boundary, overdue and reset');
